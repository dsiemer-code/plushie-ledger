// Builds tags/tag-front.svg and tags/tag-back.svg (2 x 2 in) for Clarissa Leah Makes.
// Fixed text is converted to outlines from Yu Gothic (the font on her original tags, installed with Windows),
// so the tags print the same on any device. "makes" is traced from a photo of her printed tag
// (makes-path.txt: potrace output in that photo's pixels; logo.json: where the caps sit in the same photo).
// The front keeps live text for the plushie's name and price (ids "name" and "price") and a rect "qr" for the QR code.
//
// Run on Windows:  cd tools/tag-art && npm install && node build.js
const fs = require("fs"), path = require("path"), fontkit = require("fontkit");

const FONT_DIR = process.env.FONT_DIR || "C:/Windows/Fonts";
const OUT = path.join(__dirname, "..", "..", "tags");
function load(file, ps) {
  const f = fontkit.openSync(path.join(FONT_DIR, file));
  return f.fonts ? f.fonts.find((x) => x.postscriptName === ps) || f.fonts[0] : f;
}
const F = {
  light: load("YuGothL.ttc", "YuGothic-Light"),
  regular: load("YuGothR.ttc", "YuGothic-Regular"),
  medium: load("YuGothM.ttc", "YuGothic-Medium"),
  bold: load("YuGothB.ttc", "YuGothic-Bold"),
};
const INK = "#111";
const LIVE_FONT = "Yu Gothic Medium, YuGothic, Zen Kaku Gothic New, sans-serif"; // name and price
const r2 = (s) => s.replace(/-?\d+\.\d+/g, (n) => String(+(+n).toFixed(2)));

// Text as outline path, left edge of the pen at x, baseline at y (sizes in points)
function shape(font, text, size) {
  const run = font.layout(text), s = size / font.unitsPerEm;
  let pen = 0; const glyphs = [];
  run.glyphs.forEach((g, i) => { const p = run.positions[i]; glyphs.push({ g, dx: (pen + p.xOffset) * s, dy: p.yOffset * s }); pen += p.xAdvance; });
  return { glyphs, width: pen * s, s };
}
const width = (font, text, size) => shape(font, text, size).width;
function outline(font, text, size, x, y) {
  const { glyphs, s } = shape(font, text, size);
  return glyphs.map(({ g, dx, dy }) => g.path.scale(s, -s).translate(x + dx, y - dy).toSVG()).join("");
}

// Paragraph of styled runs, wrapped to maxWidth. Returns { d, lines }.
function paragraph(runs, size, x, y, maxWidth, leading) {
  const words = [];
  for (const { font, text } of runs) for (const w of text.split(/\s+/).filter(Boolean)) words.push({ font, w });
  const space = width(F.medium, " ", size);
  const lines = []; let line = [], lineW = 0;
  for (const word of words) {
    const ww = width(word.font, word.w, size);
    if (line.length && lineW + space + ww > maxWidth) { lines.push(line); line = []; lineW = 0; }
    line.push({ ...word, ww }); lineW += (line.length > 1 ? space : 0) + ww;
  }
  if (line.length) lines.push(line);
  let d = "";
  lines.forEach((ln, i) => { let cx = x; for (const wd of ln) { d += outline(wd.font, wd.w, size, cx, y + i * leading); cx += wd.ww + space; } });
  return { d, lines: lines.length };
}

const hole = (cx, cy) => `<circle cx="${cx}" cy="${cy}" r="4.5" fill="none" stroke="#c4c4c4" stroke-width="0.5"/>`;
const instagram = (x, y, s) => `<g transform="translate(${x},${y}) scale(${s})" fill="none" stroke="${INK}" stroke-width="0.9"><rect x="0.45" y="0.45" width="8.1" height="8.1" rx="2.3"/><circle cx="4.5" cy="4.5" r="1.9"/><circle cx="6.75" cy="2.25" r="0.45" fill="${INK}" stroke="none"/></g>`;
const warningIcon = (x, y) => `<g transform="translate(${x},${y})"><path d="M8 0.8 L15.4 14 H0.6 Z" fill="none" stroke="${INK}" stroke-width="1.1" stroke-linejoin="round"/><path d="M8 5 V9.4" stroke="${INK}" stroke-width="1.3" stroke-linecap="round"/><circle cx="8" cy="11.8" r="0.8" fill="${INK}"/></g>`;

// ---------- Front ----------
function front() {
  const logo = JSON.parse(fs.readFileSync(path.join(__dirname, "logo.json"), "utf8"));
  const makes = fs.readFileSync(path.join(__dirname, "makes-path.txt"), "utf8").trim();
  const { caps, capFit, bottom } = logo;
  // caps at 100px like the photo match, then fitted to where they sit in the photo
  const capsRun = shape(F.light, "CLARISSA LEAH", 100);
  const minX = capsRun.glyphs[0].g.bbox.minX * capsRun.s;
  const capsD = outline(F.light, "CLARISSA LEAH", 100, 0, 0);
  const logoW = 112, s = logoW / (caps.x1 - caps.x0), top = 23, left = (144 - logoW) / 2;
  const logoBottom = top + (bottom - caps.y0) * s;
  const rule = +(logoBottom + 5).toFixed(2);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="2in" height="2in" viewBox="0 0 144 144">
  <!-- Clarissa Leah Makes tag, front (2 x 2 in). Generated by tools/tag-art/build.js.
       Plushie Ledger fills the text with id="name" and id="price" and draws the QR code inside the rect with id="qr".
       The light circle marks where to punch the hole. -->
  ${hole(15, 15)}
  <g fill="${INK}">
    <g transform="translate(${r2((left - caps.x0 * s).toFixed(3))},${r2((top - caps.y0 * s).toFixed(3))}) scale(${s.toFixed(5)})">
      <path transform="translate(${(caps.x0 - minX * capFit.fx).toFixed(2)},${caps.y1}) scale(${capFit.fx.toFixed(4)},${capFit.fy.toFixed(4)})" d="${r2(capsD)}"/>
      <path d="${makes}"/>
    </g>
    <path d="M36 ${rule} H108" stroke="${INK}" stroke-width="0.6"/>
    <text id="name" x="72" y="${(rule + 16).toFixed(1)}" text-anchor="middle" font-family="${LIVE_FONT}" font-weight="500" font-size="11">Plushie name</text>
    <text id="price" x="12" y="128" font-family="${LIVE_FONT}" font-weight="500" font-size="26">$00</text>
  </g>
  <rect id="qr" x="90" y="88" width="44" height="44" fill="none"/>
</svg>
`;
}

// ---------- Back ----------
function back() {
  const X = 12, W = 120, body = 5.6, lead = 6.6;
  let d = "", y = 18.5;
  d += outline(F.bold, "CARE INSTRUCTIONS", 7.2, X, y);
  y += 8;
  const care = paragraph([{ font: F.bold, text: "Spot clean only." }, { font: F.medium, text: "Dip a small cloth in warm water with mild detergent. Gently rub to remove spot. Squeeze out excess water and allow to air dry." }], body, X, y, W, lead);
  d += care.d; y += (care.lines - 1) * lead + 7;
  const iconY = y; y += 9.5;
  d += outline(F.medium, "WARNING", 12.5, X + 19, y);
  y += 7;
  d += outline(F.medium, "CHOKING HAZARD", 6.2, X + 19.5, y);
  y += 9;
  const warn = paragraph([{ font: F.medium, text: "This handmade item is created with small plastic parts that can be a choking hazard for pets and young children. Please be careful with the wear and tear of this item as the small parts may become loose over time. Use with caution. May not be suitable for children under the age of 3." }], body, X, y, W, lead);
  d += warn.d; y += (warn.lines - 1) * lead + 5;
  const ruleY = y; y += 7;
  const email = "clarissaleahmakes@gmail.com", handle = "@clarissaleahmakes";
  d += outline(F.medium, email, body, 72 - width(F.medium, email, body) / 2, y);
  y += lead;
  const hw = width(F.medium, handle, body), iconW = 5.2, gap = 2.2, start = 72 - (iconW + gap + hw) / 2;
  d += outline(F.medium, handle, body, start + iconW + gap, y);
  if (y > 139) throw new Error(`back text runs off the tag (last baseline ${y.toFixed(1)})`);
  console.log(`back: care ${care.lines} lines, warning ${warn.lines} lines, last baseline ${y.toFixed(1)} of 144`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="2in" height="2in" viewBox="0 0 144 144">
  <!-- Clarissa Leah Makes tag, back (2 x 2 in): the same on every tag. Generated by tools/tag-art/build.js.
       The light circle marks the hole; it lines up with the front's when the sheet is flipped left to right. -->
  ${hole(129, 15)}
  <path fill="${INK}" d="${r2(d)}"/>
  ${warningIcon(X, iconY)}
  <path d="M36 ${ruleY.toFixed(2)} H108" stroke="${INK}" stroke-width="0.5"/>
  ${instagram(start.toFixed(2), (y - 4.4).toFixed(2), (iconW / 9).toFixed(3))}
</svg>
`;
}

fs.writeFileSync(path.join(OUT, "tag-front.svg"), front());
fs.writeFileSync(path.join(OUT, "tag-back.svg"), back());
console.log("wrote", path.join(OUT, "tag-front.svg"), "and tag-back.svg");
